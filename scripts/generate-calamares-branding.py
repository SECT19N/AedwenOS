# Palette colours the eagle is drawn in: EagleMark `tint` -> palette key.
EAGLE_TINTS = {"primary": "primary", "primary-fg": "on-primary", "pc-fg": "on-pc"}

# Shapes from the design's `SHAPES` table.
SHAPES = {
    "baseline": {"r-win": 12, "r-inner": 8, "r-pop": 28, "r-card": 16, "r-tile": 16,
                 "ease": [0.2, 0, 0, 1], "dur": 300},
    "expressive": {"r-win": 16, "r-inner": 10, "r-pop": 32, "r-card": 20, "r-tile": 20,
                   "ease": [0.34, 1.45, 0.55, 1], "dur": 420},
}


def camel(key):
    """QML property name for a palette key. "on-x" (content colour on x)
    becomes "xFg" -- QML reads names like onPrimary as signal handlers."""
    if key == "on-s":
        return "fg"
    if key == "on-sv":
        return "fgVariant"
    fg = key.startswith("on-")
    head, *rest = (key[3:] if fg else key).split("-")
    name = head + "".join(part.capitalize() for part in rest)
    return name + "Fg" if fg else name


def rgba(hex_color, alpha):
    h = hex_color.lstrip("#")
    r, g, b = (int(h[i : i + 2], 16) for i in (0, 2, 4))
    return f"rgba({r}, {g}, {b}, {alpha})"


def load_codepoints(path):
    table = {}
    with open(path) as f:
        for line in f:
            name, cp = line.split()
            table[name] = int(cp, 16)
    missing = [n for n in ICONS if n not in table]
    if missing:
        sys.exit(f"icons missing from {path}: {', '.join(missing)}")
    return {n: table[n] for n in ICONS}


def theme_qml(p, shape, codepoints):
    colours = "\n".join(
        f'    readonly property color {camel(k)}: "{v}"' for k, v in p.items()
    )
    icons = ",\n".join(f'        "{n}": "\\u{cp:04x}"' for n, cp in codepoints.items())
    e = shape["ease"]
    return f"""// Generated by scripts/generate-calamares-branding.py -- do not edit by hand.
// Design tokens from the AedwenOS System Surfaces design (palette_lib.py).
pragma Singleton
import QtQuick

QtObject {{
{colours}
    // 8% on-surface state layer (hover)
    readonly property color state: Qt.rgba({int(p["on-s"][1:3], 16)} / 255, {int(p["on-s"][3:5], 16)} / 255, {int(p["on-s"][5:7], 16)} / 255, 0.08)

    readonly property int rWin: {shape["r-win"]}
    readonly property int rInner: {shape["r-inner"]}
    readonly property int rPop: {shape["r-pop"]}
    readonly property int rCard: {shape["r-card"]}
    readonly property int rTile: {shape["r-tile"]}

    // Spring ease and duration for shape morphs
    readonly property var ease: [{e[0]}, {e[1]}, {e[2]}, {e[3]}, 1, 1]
    readonly property int dur: {shape["dur"]}

    readonly property string font: "Roboto"
    readonly property string mono: "Roboto Mono"
    property FontLoader symbolsLoader: FontLoader {{ source: "fonts/MaterialSymbolsRounded-subset.ttf" }}
    readonly property string symbols: symbolsLoader.name

    readonly property var icons: ({{
{icons}
    }})
    function icon(name) {{ return icons[name] || "" }}
}}
"""


