#!/usr/bin/env python3
"""
Generate the design-token files for the AedwenOS Calamares branding
(iso/airootfs/etc/calamares/branding/aedwenos/), from the same palette as
every other AedwenOS theme generator (palette_lib.py):

  - Theme.qml          QML singleton: colours, radii, motion, fonts and the
                       icon-name -> codepoint table used by every QML page
  - stylesheet.qss     Qt-widget styling for the pages that are not QML
                       (the Disk/partition step), per "App widgets" in the
                       AedwenOS System Surfaces design
  - branding.desc      only the `style:` block (sidebar colours) is rewritten
  - eagle-<colour>.png  the logo pre-tinted in the palette colours EagleMark
                       uses (a pre-rendered tint works on every Qt Quick
                       backend; a MultiEffect mask needs shader support)
  - fonts/MaterialSymbolsRounded-subset.ttf + LICENSE
                       Material Symbols Rounded (Apache-2.0), subset to the
                       icons in ICONS so the branding stays small. The
                       variable axes (FILL, wght, ...) are kept.

The full font and its codepoint table are downloaded from
github.com/google/material-design-icons unless --symbols-font/--codepoints
point at local copies.

Usage:
    scripts/generate-calamares-branding.py [--seed violet] [--light] [--baseline]

Requires fonttools and python-cairo.
"""

