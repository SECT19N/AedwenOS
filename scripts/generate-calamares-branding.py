def write_style_block(path, p):
    block = (
        "style:\n"
        f'    SidebarBackground:        "{p["sc-low"]}"\n'
        f'    SidebarText:              "{p["on-sv"]}"\n'
        f'    SidebarTextCurrent:       "{p["on-sec-c"]}"\n'
        f'    SidebarBackgroundCurrent: "{p["sec-c"]}"\n'
    )
    with open(path) as f:
        src = f.read()
    new, n = re.subn(r"^style:\n(?:[ \t]+\S.*\n)*", block, src, flags=re.M)
    if n != 1:
        sys.exit(f"could not find a single `style:` block in {path}")
    with open(path, "w") as f:
        f.write(new)


def tinted_eagles(out, p, size=256):
    """logo.png (white eagle on transparency) as eagle-<tint>.png per tint."""
    logo = cairo.ImageSurface.create_from_png(os.path.join(out, "logo.png"))
    # Crop to the eagle itself: logo.png carries wide transparent margins.
    w, h_, stride = logo.get_width(), logo.get_height(), logo.get_stride()
    data = logo.get_data()
    rows = [y for y in range(h_) if any(data[y * stride + x * 4 + 3] for x in range(0, w, 2))]
    cols = [x for x in range(w) if any(data[y * stride + x * 4 + 3] for y in range(rows[0], rows[-1] + 1, 2))]
    x0, y0, bw, bh = cols[0], rows[0], cols[-1] - cols[0] + 1, rows[-1] - rows[0] + 1
    scale = size / max(bw, bh)
    for tint, key in EAGLE_TINTS.items():
        h = p[key].lstrip("#")
        rgb = [int(h[i : i + 2], 16) / 255 for i in (0, 2, 4)]
        surface = cairo.ImageSurface(cairo.FORMAT_ARGB32, size, size)
        ctx = cairo.Context(surface)
        ctx.translate((size - bw * scale) / 2, (size - bh * scale) / 2)
        ctx.scale(scale, scale)
        ctx.set_source_rgb(*rgb)
        ctx.mask_surface(logo, -x0, -y0)
        surface.write_to_png(os.path.join(out, f"eagle-{tint}.png"))


def fetch(url, dest):
    print(f"downloading {url}")
    urllib.request.urlretrieve(url, dest)
    return dest


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=BRANDING)
    ap.add_argument("--seed", default=DEFAULT_SEED)
    ap.add_argument("--light", action="store_true")
    ap.add_argument("--baseline", action="store_true")
    ap.add_argument("--symbols-font", help="local MaterialSymbolsRounded[...].ttf")
    ap.add_argument("--codepoints", help="local MaterialSymbolsRounded[...].codepoints")
    args = ap.parse_args()

    p = palette(SEEDS[args.seed], dark=not args.light, expressive=not args.baseline)
    shape = SHAPES["baseline" if args.baseline else "expressive"]

    with tempfile.TemporaryDirectory() as tmp:
        font = args.symbols_font or fetch(FONT_URL + ".ttf", os.path.join(tmp, "msr.ttf"))
        cps = args.codepoints or fetch(FONT_URL + ".codepoints", os.path.join(tmp, "msr.codepoints"))
        codepoints = load_codepoints(cps)

        fonts_dir = os.path.join(args.out, "fonts")
        os.makedirs(fonts_dir, exist_ok=True)
        subset = os.path.join(fonts_dir, "MaterialSymbolsRounded-subset.ttf")
        subprocess.run(
            [sys.executable, "-m", "fontTools.subset", font,
             "--unicodes=" + ",".join(f"U+{cp:04X}" for cp in codepoints.values()),
             "--layout-features=*", "--no-hinting", "--output-file=" + subset],
            check=True,
        )
        fetch(LICENSE_URL, os.path.join(fonts_dir, "LICENSE"))

    with open(os.path.join(args.out, "Theme.qml"), "w") as f:
        f.write(theme_qml(p, shape, codepoints))
    with open(os.path.join(args.out, "stylesheet.qss"), "w") as f:
        f.write(stylesheet(p, shape))
    write_style_block(os.path.join(args.out, "branding.desc"), p)
    tinted_eagles(args.out, p)

    print(f"Wrote Theme.qml, stylesheet.qss, branding.desc style and icon font ({len(codepoints)} icons) to {args.out}")


if __name__ == "__main__":
    main()
