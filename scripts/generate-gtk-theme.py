#!/usr/bin/env python3
"""
Generate the AedwenOS GTK3 + GTK4/libadwaita theme from the same palette
used by the KDE colour scheme (scripts/palette_lib.py), matching the
"GTK & libadwaita apps" section of the AedwenOS System Surfaces design:
same 48px header bar with a centred title and a monochrome circular close
button, same pill buttons / switches / boxed list rows as the Qt widgets,
same seed colour.

Usage:
    scripts/generate-gtk-theme.py [--out DIR]
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from palette_lib import (DEFAULT_SEED, SEEDS, VARIANTS, palette, palette_contrast,  # noqa: E402
                         shapes, srgb_hex_to_oklch)

# Shape tokens of the variant being written (palette_lib.SHAPES); set by
# use_variant() before any CSS is generated.
R_WIN = R_INNER = R_CARD = CTL_HOVER = None


def use_variant(variant):
    global R_WIN, R_INNER, R_CARD, CTL_HOVER
    sh = shapes(variant)
    R_WIN, R_INNER, R_CARD = f"{sh['r_win']}px", f"{sh['r_inner']}px", f"{sh['r_card']}px"
    # window buttons: Expressive morphs circle -> rounded square on hover
    CTL_HOVER = f"{sh['ctl_hover_r']}px" if sh["ctl_hover_r"] is not None else "9999px"


def define_colors(p):
    lines = [f"@define-color ae_{k.replace('-', '_')} {v};" for k, v in p.items()]
    return "\n".join(lines)


# GTK's built-in theme goes underneath, so widgets the rules below don't
# cover still get a complete style instead of unstyled defaults.
GTK3_BASE = "resource:///org/gtk/libgtk/theme/Adwaita/gtk-contained{}.css"
GTK4_BASE = "resource:///org/gtk/libgtk/theme/Default/Default-{}.css"


# Appended to every stylesheet at high contrast (Appearance > Contrast): 2px
# full-strength outlines on controls and the 3px keyboard focus ring.
HC_CSS = """
/* high contrast */
button, entry, spinbutton, combobox button, row.activatable, switch, scale trough, popover > contents, menu {{
  border: 2px solid {fg};
}}
button:hover, row.activatable:hover {{ background-color: alpha({fg}, 0.24); }}
*:focus-visible {{
  outline: 3px solid {accent};
  outline-offset: 2px;
}}
"""


def hc_css(p):
    return HC_CSS.format(fg=p["on-s"], accent=p["primary"])


