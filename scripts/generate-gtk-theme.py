def gtk4_css(p, dark):
    # GTK4 + libadwaita apps mostly pick up accent/colour-scheme from the
    # xdg-desktop-portal-kde portal (see kdeglobals AccentColor); this
    # stylesheet is a fallback for GTK4 apps that load a named theme
    # directly rather than going through libadwaita's StyleManager.
    return gtk3_css(p, dark).replace(
        "/* AedwenOS GTK3 theme -- generated by scripts/generate-gtk-theme.py, do not edit by hand */",
        "/* AedwenOS GTK4 theme -- generated by scripts/generate-gtk-theme.py, do not edit by hand */\n"
        "/* libadwaita apps ignore named themes; see the user stylesheet in /etc/skel/.config/gtk-4.0/gtk.css. */",
    ).replace(
        GTK3_BASE.format("-dark" if dark else ""),
        GTK4_BASE.format("dark" if dark else "light"),
    )


def adwaita_vars(p):
    """libadwaita named colours (CSS variables, libadwaita >= 1.6)."""
    pairs = {
        "accent-bg-color": p["primary"], "accent-fg-color": p["on-primary"], "accent-color": p["primary"],
        "window-bg-color": p["surface"], "window-fg-color": p["on-s"],
        "view-bg-color": p["surface"], "view-fg-color": p["on-s"],
        "headerbar-bg-color": p["sc"], "headerbar-fg-color": p["on-s"],
        "headerbar-backdrop-color": p["surface"],
        "sidebar-bg-color": p["sc-low"], "sidebar-fg-color": p["on-s"],
        "card-bg-color": p["sc-low"], "card-fg-color": p["on-s"],
        "dialog-bg-color": p["sc-high"], "dialog-fg-color": p["on-s"],
        "popover-bg-color": p["sc-high"], "popover-fg-color": p["on-s"],
        "destructive-bg-color": p["err-c"], "destructive-fg-color": p["on-err-c"],
        "destructive-color": p["err"], "error-color": p["err"],
    }
    return "\n".join(f"    --{k}: {v};" for k, v in pairs.items())


def libadwaita_css(seed):
    """User stylesheet for GTK4/libadwaita apps (~/.config/gtk-4.0/gtk.css):
    the palette as libadwaita's colour variables for both colour schemes,
    plus the section 02 shapes (48px header bar, round close button, grouped
    rows with gaps)."""
    H = SEEDS[seed]
    dark, light = palette(H, True, True), palette(H, False, True)
    return f"""/* AedwenOS libadwaita overrides -- generated by scripts/generate-gtk-theme.py, do not edit by hand */

@media (prefers-color-scheme: dark) {{
  :root {{
{adwaita_vars(dark)}
  }}
}}
@media (prefers-color-scheme: light) {{
  :root {{
{adwaita_vars(light)}
  }}
}}

headerbar {{
  min-height: 48px;
}}
windowcontrols > button.close > image {{
  background-color: color-mix(in srgb, var(--window-fg-color) 12%, transparent);
}}

.boxed-list,
.boxed-list-separate {{
  background: none;
  box-shadow: none;
}}
.boxed-list > row {{
  min-height: 56px;
  margin-bottom: 2px;
  border: none;
  border-radius: 4px;
  background-color: var(--card-bg-color);
}}
.boxed-list > row:first-child {{
  border-top-left-radius: {R_CARD};
  border-top-right-radius: {R_CARD};
}}
.boxed-list > row:last-child {{
  margin-bottom: 0;
  border-bottom-left-radius: {R_CARD};
  border-bottom-right-radius: {R_CARD};
}}

switch {{
  min-width: 44px;
  min-height: 26px;
}}
"""


def write_variant(out_root, seed, dark, expressive):
    H = SEEDS[seed]
    p = palette(H, dark, expressive)
    theme_name = f"AedwenOS-{seed.capitalize()}-{'Dark' if dark else 'Light'}"

    for gtk_dir, css in (
        ("gtk-3.0", gtk3_css(p, dark)),
        ("gtk-4.0", gtk4_css(p, dark)),
    ):
        d = os.path.join(out_root, theme_name, gtk_dir)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "gtk.css"), "w") as f:
            f.write(css)
        # gtk-dark.css is what GTK4 loads when prefer-dark-theme is set
        with open(os.path.join(d, "gtk-dark.css"), "w") as f:
            f.write(css)

    idx = os.path.join(out_root, theme_name, "index.theme")
    with open(idx, "w") as f:
        f.write(f"""[Desktop Entry]
Type=X-GNOME-Metatheme
Name={theme_name}
Comment=AedwenOS · {seed.capitalize()} ({"Dark" if dark else "Light"}), generated from the system seed colour

[X-GNOME-Metatheme]
GtkTheme={theme_name}
MetacityTheme={theme_name}
IconTheme=breeze-dark
CursorTheme=Aedwen
ButtonLayout=close:
""")
    return theme_name


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="iso/airootfs/usr/share/themes")
    ap.add_argument("--seed", default=None)
    ap.add_argument(
        "--libadwaita-out", default="iso/airootfs/etc/skel/.config/gtk-4.0/gtk.css"
    )
    args = ap.parse_args()

    seeds = [args.seed] if args.seed else SEEDS.keys()
    written = []
    for seed in seeds:
        for dark in (True, False):
            written.append(write_variant(args.out, seed, dark, expressive=True))

    with open(args.libadwaita_out, "w") as f:
        f.write(libadwaita_css(args.seed or DEFAULT_SEED))

    print(f"Wrote {len(written)} GTK theme variants to {args.out}")
    print(f"Wrote libadwaita stylesheet to {args.libadwaita_out}")
    print("Default: AedwenOS-" + DEFAULT_SEED.capitalize() + "-Dark")


if __name__ == "__main__":
    main()
