#!/usr/bin/env python3
"""
Generate the AedwenOS GTK3 + GTK4/libadwaita theme from the same palette
used by the KDE colour scheme (scripts/palette_lib.py), matching the
"GTK & libadwaita apps" section of the AedwenOS System Surfaces design:
same 48px header bar with a centred title and a monochrome circular close
button, same pill buttons / switches / boxed list rows as the Qt widgets,
same seed colour.

Usage:
    scripts/generate-gtk-theme.py [--out DIR]
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from palette_lib import DEFAULT_SEED, SEEDS, palette  # noqa: E402

R_WIN, R_INNER, R_CARD = "16px", "10px", "20px"  # expressive shapes


def define_colors(p):
    lines = [f"@define-color ae_{k.replace('-', '_')} {v};" for k, v in p.items()]
    return "\n".join(lines)


# GTK's built-in theme goes underneath, so widgets the rules below don't
# cover still get a complete style instead of unstyled defaults.
GTK3_BASE = "resource:///org/gtk/libgtk/theme/Adwaita/gtk-contained{}.css"
GTK4_BASE = "resource:///org/gtk/libgtk/theme/Default/Default-{}.css"


