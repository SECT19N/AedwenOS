def gtk4_css(p, dark):
    # GTK4 + libadwaita apps mostly pick up accent/colour-scheme from the
    # xdg-desktop-portal-kde portal (see kdeglobals AccentColor); this
    # stylesheet is a fallback for GTK4 apps that load a named theme
    # directly rather than going through libadwaita's StyleManager.
    return gtk3_css(p, dark).replace(
        "/* AedwenOS GTK3 theme -- generated by scripts/generate-gtk-theme.py, do not edit by hand */",
        "/* AedwenOS GTK4 theme -- generated by scripts/generate-gtk-theme.py, do not edit by hand */\n"
        "/* libadwaita apps ignore named themes; see the user stylesheet in /etc/skel/.config/gtk-4.0/gtk.css. */",
    ).replace(
        GTK3_BASE.format("-dark" if dark else ""),
        GTK4_BASE.format("dark" if dark else "light"),
    )


def adwaita_vars(p):
    """libadwaita named colours (CSS variables, libadwaita >= 1.6)."""
    pairs = {
        "accent-bg-color": p["primary"], "accent-fg-color": p["on-primary"], "accent-color": p["primary"],
        "window-bg-color": p["surface"], "window-fg-color": p["on-s"],
        "view-bg-color": p["surface"], "view-fg-color": p["on-s"],
        "headerbar-bg-color": p["surface"], "headerbar-fg-color": p["on-s"],
        "headerbar-backdrop-color": p["surface"],
        "sidebar-bg-color": p["sc-low"], "sidebar-fg-color": p["on-s"],
        "card-bg-color": p["sc-low"], "card-fg-color": p["on-s"],
        "dialog-bg-color": p["sc-high"], "dialog-fg-color": p["on-s"],
        "popover-bg-color": p["sc-high"], "popover-fg-color": p["on-s"],
        "destructive-bg-color": p["err-c"], "destructive-fg-color": p["on-err-c"],
        "destructive-color": p["err"], "error-color": p["err"],
    }
    return "\n".join(f"    --{k}: {v};" for k, v in pairs.items())


def libadwaita_css(H, variant, contrast="standard"):
    """User stylesheet for GTK4/libadwaita apps (~/.config/gtk-4.0/gtk.css):
    the palette as libadwaita's colour variables for both colour schemes,
    plus the section 02 shapes (48px header bar, round close button, grouped
    rows with gaps)."""
    ex = variant == "expressive"
    dark = palette_contrast(H, True, ex, contrast)
    light = palette_contrast(H, False, ex, contrast)
    css = f"""/* AedwenOS libadwaita overrides -- generated by scripts/generate-gtk-theme.py, do not edit by hand */

@media (prefers-color-scheme: dark) {{
  :root {{
{adwaita_vars(dark)}
  }}
}}
@media (prefers-color-scheme: light) {{
  :root {{
{adwaita_vars(light)}
  }}
}}

headerbar {{
  min-height: 48px;
}}
/* window buttons as in the KDE title bars (generate-aurorae-theme.py) */
windowcontrols > button {{
  min-width: 32px;
  min-height: 32px;
  padding: 0;
}}
windowcontrols > button > image {{
  min-width: 32px;
  min-height: 32px;
  padding: 0;
  border-radius: 9999px;
  background-color: color-mix(in srgb, var(--window-fg-color) 10%, transparent);
  transition: border-radius 180ms ease, background-color 150ms ease;
}}
windowcontrols > button:hover > image,
windowcontrols > button:active > image {{
  border-radius: {CTL_HOVER};
  background-color: color-mix(in srgb, var(--accent-bg-color) 28%, transparent);
}}
windowcontrols > button.close:hover > image,
windowcontrols > button.close:active > image {{
  background-color: var(--destructive-bg-color);
  color: var(--destructive-fg-color);
}}

.boxed-list,
.boxed-list-separate {{
  background: none;
  box-shadow: none;
}}
.boxed-list > row {{
  min-height: 56px;
  margin-bottom: 2px;
  border: none;
  border-radius: 4px;
  background-color: var(--card-bg-color);
}}
.boxed-list > row:first-child {{
  border-top-left-radius: {R_CARD};
  border-top-right-radius: {R_CARD};
}}
.boxed-list > row:last-child {{
  margin-bottom: 0;
  border-bottom-left-radius: {R_CARD};
  border-bottom-right-radius: {R_CARD};
}}

switch {{
  min-width: 44px;
  min-height: 26px;
}}
"""
    if contrast == "high":
        # libadwaita has one stylesheet for both colour schemes
        css += "@media (prefers-color-scheme: dark) {\n" + hc_css(dark) + "}\n"
        css += "@media (prefers-color-scheme: light) {\n" + hc_css(light) + "}\n"
    return css


def write_variant(out_root, seed, dark, variant, contrast="standard"):
    use_variant(variant)
    H = SEEDS[seed]
    p = palette_contrast(H, dark, variant == "expressive", contrast)
    # Expressive keeps the original names; stock M3 gets a -Baseline suffix
    suffix = ("" if variant == "expressive" else "-Baseline") + ("-HighContrast" if contrast == "high" else "")
    theme_name = f"AedwenOS-{seed.capitalize()}-{'Dark' if dark else 'Light'}{suffix}"

    for gtk_dir, css in (
        ("gtk-3.0", gtk3_css(p, dark) + (hc_css(p) if contrast == "high" else "")),
        ("gtk-4.0", gtk4_css(p, dark) + (hc_css(p) if contrast == "high" else "")),
    ):
        d = os.path.join(out_root, theme_name, gtk_dir)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "gtk.css"), "w") as f:
            f.write(css)
        # gtk-dark.css is what GTK4 loads when prefer-dark-theme is set
        with open(os.path.join(d, "gtk-dark.css"), "w") as f:
            f.write(css)

    idx = os.path.join(out_root, theme_name, "index.theme")
    with open(idx, "w") as f:
        f.write(f"""[Desktop Entry]
Type=X-GNOME-Metatheme
Name={theme_name}
Comment=AedwenOS · {seed.capitalize()} ({"Dark" if dark else "Light"}), generated from the system seed colour

[X-GNOME-Metatheme]
GtkTheme={theme_name}
MetacityTheme={theme_name}
IconTheme=breeze-dark
CursorTheme=Aedwen
ButtonLayout=:minimize,maximize,close
""")
    return theme_name


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="iso/airootfs/usr/share/themes")
    ap.add_argument("--seed", default=None)
    ap.add_argument("--variant", default="expressive", choices=VARIANTS,
                    help="M3 Expressive (shipped) or stock M3 (baseline)")
    ap.add_argument(
        "--libadwaita-out", default="iso/airootfs/etc/skel/.config/gtk-4.0/gtk.css"
    )
    ap.add_argument("--contrast", default="standard", choices=("standard", "high"),
                    help="high: write the -HighContrast theme set (2px outlines, focus ring)")
    ap.add_argument("--accent", default=None,
                    help="#rrggbb accent: write only the libadwaita stylesheet for it (aedwen-apps)")
    args = ap.parse_args()

    if args.accent:
        use_variant(args.variant)
        H = srgb_hex_to_oklch(args.accent)[2]
        os.makedirs(os.path.dirname(os.path.abspath(args.libadwaita_out)), exist_ok=True)
        with open(args.libadwaita_out, "w") as f:
            f.write(libadwaita_css(H, args.variant, args.contrast))
        return

    seeds = [args.seed] if args.seed else SEEDS.keys()
    written = []
    for seed in seeds:
        for dark in (True, False):
            written.append(write_variant(args.out, seed, dark, args.variant, args.contrast))

    use_variant(args.variant)
    if args.contrast == "standard":      # the skel stylesheet stays the standard one
        with open(args.libadwaita_out, "w") as f:
            f.write(libadwaita_css(SEEDS[args.seed or DEFAULT_SEED], args.variant))

    print(f"Wrote {len(written)} GTK theme variants to {args.out}")
    print(f"Wrote libadwaita stylesheet to {args.libadwaita_out}")
    print("Default: AedwenOS-" + DEFAULT_SEED.capitalize() + "-Dark")


if __name__ == "__main__":
    main()
